"""nginx backend.
`rmon setup` writes two static files:
  /etc/rmon/nginx/rmon-http.conf   -> `include` it inside http { }   (JSON access log with the fingerprint fields + the state maps)
  /etc/rmon/nginx/rmon-guard.conf  -> `include` it inside each server { } you want protected
The guard rewrites /etc/rmon/nginx/rmon-state.conf (included by rmon-http.conf) and reloads nginx after `nginx -t`, rolling back on failure."""
import os

from . import base


class NginxBackend:
    name = "nginx"

    def __init__(self, cfg):
        self.cfg = cfg
        self.dir = "/etc/rmon/nginx"
        self.state_file = os.path.join(self.dir, "rmon-state.conf")

    def render(self, snap):
        geo = "".join("\t%s 1;\n" % t for t in snap["bans"]) + "".join("\t%s 2;\n" % t for t in sorted(set(snap["challenges"]) - set(snap["bans"])))
        fp = "".join("\t%s 1;\n" % self._fp_key(c) for c in snap["fpbans"] if base.writable_fp(c))
        return ("# managed by rmon - do not edit\ngeo $rmon_ip_state {\n\tdefault 0;\n" + geo + "}\n"
                'map "$http_user_agent|~|$http_accept_language|~|$http_accept_encoding|~|$http_sec_ch_ua|~|$http_sec_ch_ua_platform" $rmon_fp_state {\n\tdefault 0;\n' + fp + "}\n"
                'map "$rmon_ip_state$rmon_fp_state" $rmon_state {\n\tdefault 0;\n\t"10" 1; "11" 1; "01" 1; "21" 1; "20" 2;\n}\n')

    @staticmethod
    def _fp_key(c):
        key = "|~|".join(c[k] for k, _ in base.FP_FIELDS)
        return '"' + key.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'

    def apply(self, snap):
        text = self.render(snap)
        try:
            old = open(self.state_file, encoding="utf-8").read()
        except OSError:
            old = None
        if old == text:
            return True
        base.write_if_changed(self.state_file, text)
        rc, out = base.run(["nginx", "-t"])
        if rc == 0:
            rc, out = base.run(["systemctl", "reload", "nginx"])
        if rc != 0:
            base.write_if_changed(self.state_file, old if old is not None else self.render({"bans": [], "challenges": [], "fpbans": []}))
            base.run(["systemctl", "reload", "nginx"])
            return False
        return True


def http_conf(cfg):
    log = cfg["web"].get("log_path") or "/var/log/nginx/rmon-access.log"
    return f"""# Generated by `rmon setup` - include inside http {{ }}
log_format rmon_json escape=json '{{"ip":"$remote_addr","host":"$host","method":"$request_method","uri":"$request_uri","status":$status,"bytes":$body_bytes_sent,'
	'"ua":"$http_user_agent","al":"$http_accept_language","ae":"$http_accept_encoding","sua":"$http_sec_ch_ua","sup":"$http_sec_ch_ua_platform"}}';
access_log {log} rmon_json;
include /etc/rmon/nginx/rmon-state.conf;
"""


def guard_conf(cfg):
    port = cfg["challenge"]["port"]
    return f"""# Generated by `rmon setup` - include inside each server {{ }} to protect
location ^~ /__rmon/ {{
	proxy_pass http://127.0.0.1:{port};
	proxy_set_header X-Rmon-Ip $remote_addr;
	proxy_set_header Host $host;
	proxy_set_header X-Forwarded-Proto $scheme;
}}
set $rmon_act 0;
if ($rmon_state != 0) {{ set $rmon_act $rmon_state; }}
if ($uri ~* ^/__rmon/) {{ set $rmon_act 0; }}
if ($rmon_act = 1) {{ rewrite ^ /__rmon/p/ban last; }}
if ($rmon_act = 2) {{ rewrite ^ /__rmon/p/challenge last; }}
"""
