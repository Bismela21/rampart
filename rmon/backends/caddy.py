"""Caddy backend. `rmon setup` writes /etc/rmon/caddy/rmon.caddy once (the `rmon_guard` snippet); you add `import rmon_guard` to your sites.
The guard rewrites /etc/rmon/caddy/rmon-state.conf (three named matchers) and reloads Caddy after validating it, rolling back on failure."""
import os

from . import base

NONE_IP = "192.0.2.254"   # documentation address: keeps the matcher valid when the list is empty
NONE_FP = '{http.request.header.User-Agent} == "__rmon_no_fingerprint__"'


class CaddyBackend:
    name = "caddy"

    def __init__(self, cfg):
        self.cfg = cfg
        self.dir = os.path.join("/etc/rmon", "caddy")
        self.state_file = os.path.join(self.dir, "rmon-state.conf")
        self.caddyfile = cfg["web"].get("caddyfile") or "/etc/caddy/Caddyfile"

    def render(self, snap):
        fps = ["(" + " && ".join("{http.request.header.%s} == %s" % (h, base.cel_quote(c[k])) for k, h in base.FP_FIELDS) + ")" for c in snap["fpbans"] if base.writable_fp(c)]
        return ("@rmon_banned client_ip %s\n@rmon_fpban expression `%s`\n@rmon_challenge client_ip %s\n"
                % (" ".join(snap["bans"]) or NONE_IP, " || ".join(fps) or NONE_FP, " ".join(sorted(set(snap["challenges"]) - set(snap["bans"]))) or NONE_IP))

    def apply(self, snap):
        text = self.render(snap)
        try:
            old = open(self.state_file, encoding="utf-8").read()
        except OSError:
            old = None
        if old == text:
            return True
        base.write_if_changed(self.state_file, text)
        rc, out = base.run(["caddy", "validate", "--config", self.caddyfile, "--adapter", "caddyfile"])
        if rc == 0:
            rc, out = base.run(["systemctl", "reload", "caddy"])
        if rc != 0:   # Caddy refused the list: put the previous one back, never leave the server in a broken state
            base.write_if_changed(self.state_file, old if old is not None else self.render({"bans": [], "challenges": [], "fpbans": []}))
            base.run(["systemctl", "reload", "caddy"])
            return False
        return True


def snippet(cfg):
    """The static `rmon_guard` snippet (written by `rmon setup`)."""
    port = cfg["challenge"]["port"]
    log = cfg["web"].get("log_path") or "/var/log/caddy/rmon-access.log"
    return f"""# Generated by `rmon setup`. Add `import rmon_guard` inside every site block you want protected.
(rmon_proxy) {{
	reverse_proxy 127.0.0.1:{port} {{
		header_up X-Rmon-Ip {{client_ip}}
	}}
}}

(rmon_guard) {{
	log {{
		output file {log} {{
			roll_size 20MiB
			roll_keep 3
		}}
		format filter {{
			wrap json
			fields {{
				request>headers delete
				resp_headers delete
			}}
		}}
	}}
	log_append fp_ua "{{http.request.header.User-Agent}}"
	log_append fp_al "{{http.request.header.Accept-Language}}"
	log_append fp_ae "{{http.request.header.Accept-Encoding}}"
	log_append fp_sua "{{http.request.header.Sec-Ch-Ua}}"
	log_append fp_sup "{{http.request.header.Sec-Ch-Ua-Platform}}"
	import /etc/rmon/caddy/rmon-state.conf
	handle /__rmon/* {{
		import rmon_proxy
	}}
	handle @rmon_banned {{
		rewrite * /__rmon/p/ban
		import rmon_proxy
	}}
	handle @rmon_fpban {{
		rewrite * /__rmon/p/ban
		import rmon_proxy
	}}
	handle @rmon_challenge {{
		rewrite * /__rmon/p/challenge
		import rmon_proxy
	}}
}}
"""
